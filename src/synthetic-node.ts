import { NODE_SCHEMA, type NodeSample } from './node-capture.ts';

/** A small, deterministic time series for trying the node viewer without a cluster capture. */
export function syntheticNodeRecording(): string {
  const mib = 1048576;
  const started = Date.parse('2026-01-01T00:00:00Z');
  const memory = [820, 822, 851, 878, 866, 854];
  const podMemory = [null, 18, 42, 70, 62, 0];
  const faults = [1000, 1100, 1700, 2400, 2660, 2740];
  const network = [10000, 13000, 21000, 31000, 39000, 45000];
  const samples: NodeSample[] = memory.map((rss, index) => {
    const sourceTime = new Date(started + index * 5000).toISOString();
    const podRss = podMemory[index];
    return {
      sourceTimes: { cpu: sourceTime, memory: sourceTime, network: sourceTime },
      node: {
        cpuUsageNanoCores: [180, 210, 380, 510, 300, 190][index] * 1000000,
        memoryUsageBytes: (rss + 290) * mib,
        memoryWorkingSetBytes: (rss + 120) * mib,
        memoryRssBytes: rss * mib,
        memoryAvailableBytes: (4096 - rss - 290) * mib,
        pageFaults: faults[index], majorPageFaults: [4, 4, 5, 5, 5, 5][index],
        memoryPsiSomeAvg10: [0.02, 0.02, 0.08, 0.11, 0.07, 0.03][index],
        memoryPsiFullAvg10: 0,
        networkRxBytes: network[index], networkTxBytes: network[index] / 2,
        fsUsedBytes: 520 * mib, processCount: [82, 84, 87, 89, 87, 82][index], processLimit: 4096,
      },
      pod: podRss === null ? null : {
        cpuUsageNanoCores: [0, 20, 150, 230, 90, 0][index] * 1000000,
        memoryWorkingSetBytes: (podRss + (podRss ? 6 : 0)) * mib,
        memoryRssBytes: podRss * mib,
        pageFaults: [0, 40, 270, 520, 650, 650][index], majorPageFaults: 0,
        networkRxBytes: [0, 500, 1800, 3600, 4500, 4500][index],
        networkTxBytes: [0, 300, 1100, 2300, 3100, 3100][index],
      },
    };
  });
  const entries = [
    { elapsedMs: 0, type: 'metadata', data: {
      environment: 'synthetic demo', context: 'example', node: 'demo-node',
      source: 'Generated by Forkscape · synthetic values', namespace: 'demo', podName: 'prefork-example',
    } },
    { elapsedMs: 0, type: 'sample', data: samples[0] },
    { elapsedMs: 2500, type: 'marker', data: { name: 'Pod scheduled' } },
    { elapsedMs: 5000, type: 'sample', data: samples[1] },
    { elapsedMs: 7500, type: 'marker', data: { name: 'Pod running' } },
    { elapsedMs: 10000, type: 'sample', data: samples[2] },
    { elapsedMs: 15000, type: 'sample', data: samples[3] },
    { elapsedMs: 20000, type: 'sample', data: samples[4] },
    { elapsedMs: 22500, type: 'marker', data: { name: 'Pod succeeded' } },
    { elapsedMs: 25000, type: 'sample', data: samples[5] },
    { elapsedMs: 25001, type: 'end', data: { status: 'ok' } },
  ];
  return entries.map((entry, seq) => JSON.stringify({
    schema: NODE_SCHEMA, runId: 'synthetic-node-startup', seq,
    at: new Date(started + entry.elapsedMs).toISOString(), ...entry,
  })).join('\n') + '\n';
}
