// Writes public/recordings/synthetic-gunicorn-boot.json: a synthetic Forkscape recording of a preloaded Gunicorn boot.
// It is generated, not measured: it shows the recording format and exercises the replay. Run with
//   node --experimental-strip-types scripts/make_sample_recording.ts
import { mkdirSync, writeFileSync } from 'node:fs';

const PAGE = 4096;
const MASTER = 1236, WORKERS = [1237, 1238], REPLACEMENT = 1239;
const events: Record<string, unknown>[] = [];
let now = 0;
const hex = (value: number) => `0x${value.toString(16)}`;
const emit = (name: string, pid: number, args: Record<string, unknown> = {}, extra: Record<string, unknown> = {}) => events.push({ ph: 'i', s: 'p', name, pid, tid: pid, ts: now, args, ...extra });
const pause = (us: number) => { now += us; };
const mmap = (pid: number, addr: number, pages: number, extra: Record<string, unknown>) => { emit('mmap', pid, { addr: hex(addr), len: pages * PAGE, ...extra }); pause(20); };
// A deterministic scatter, so the file is the same on every run.
let seed = 7;
const random = () => (seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31;
const pick = (count: number, of: number) => { const chosen = new Set<number>(); while (chosen.size < count) chosen.add(Math.floor(random() * of)); return [...chosen].sort((a, b) => a - b); };
const touch = (pid: number, addr: number, pages: number[], write: boolean, spacing = 40) => pages.forEach(page => { emit('fault', pid, { addr: hex(addr + page * PAGE + 16), write }); pause(spacing); });
const slice = (name: string, pid: number, args: Record<string, unknown>, body: () => void, cat = '') => {
  const start = now, index = events.length;
  events.push({ ph: 'X', name, pid, tid: pid, ts: start, dur: 0, args, ...(cat ? { cat } : {}) });
  pause(10); body(); pause(10);
  events[index].dur = now - start;
};

// Address-space layout, as /proc/<pid>/maps would show it after exec.
const TEXT = 0x400000, DATA = 0x5a0000, LIBC = 0x7f1000000000, HEAP = 0x1a00000, STACK = 0x7ffd00000000;
const DJANGO = 0x7f2000000000, CATALOG = 0x7f2000100000, URLCONF = 0x7f2000200000;

events.push({ ph: 'M', name: 'forkscape', pid: 0, args: {
  version: 1, page_size: PAGE, synthetic: true,
  title: 'Synthetic example: a preloaded Gunicorn boot',
  source: 'Generated by scripts/make_sample_recording.ts, not measured',
  notes: 'Two sync workers with preload_app, their first requests, a catalog scan in each, and one worker recycled by max_requests. Sizes are small so every page stays readable.',
} });
events.push({ ph: 'M', name: 'process_name', pid: MASTER, args: { name: 'gunicorn: master [app]' } });
for (const pid of [...WORKERS, REPLACEMENT]) events.push({ ph: 'M', name: 'process_name', pid, args: { name: 'gunicorn: worker [app]' } });

emit('exec', MASTER, { comm: 'gunicorn' });
pause(50);
mmap(MASTER, TEXT, 384, { file: '/usr/bin/python3.12', perms: 'r-xp', offset: 0 });
mmap(MASTER, DATA, 8, { file: '/usr/bin/python3.12', perms: 'rw-p', offset: 0x1a0000 });
mmap(MASTER, LIBC, 96, { file: '/usr/lib/x86_64-linux-gnu/libc.so.6', perms: 'r-xp', offset: 0 });
mmap(MASTER, HEAP, 512, { name: '[heap]', perms: 'rw-p' });
mmap(MASTER, STACK, 33, { name: '[stack]', perms: 'rw-p' });
// The interpreter starts: it runs code from the page cache, writes its data segment, and builds its first objects.
touch(MASTER, TEXT, pick(64, 160), false);
touch(MASTER, LIBC, pick(24, 64), false);
touch(MASTER, DATA, [0, 1, 2, 3, 4, 5, 6, 7], true);
touch(MASTER, HEAP, Array.from({ length: 64 }, (_, page) => page), true);
touch(MASTER, STACK, [25, 26, 27, 28, 29, 30, 31, 32], true);

// preload_app imports the application before forking.
pause(80_000);
slice('import', MASTER, { module: 'django' }, () => {
  mmap(MASTER, DJANGO, 256, { name: 'obmalloc arena', perms: 'rw-p' });
  ['django.conf', 'django.db', 'django.http'].forEach((module, index) => slice('import', MASTER, { module }, () => touch(MASTER, DJANGO, Array.from({ length: 32 }, (_, page) => index * 32 + page), true)));
});
pause(80_000);
slice('import', MASTER, { module: 'app.catalog' }, () => {
  mmap(MASTER, CATALOG, 256, { name: 'catalog arena', perms: 'rw-p' });
  touch(MASTER, CATALOG, Array.from({ length: 256 }, (_, page) => page), true, 20);
});
pause(80_000);
emit('open', MASTER, { fd: 3, object: 'socket:[18342]', kind: 'socket', name: '0.0.0.0:8000' });
pause(2_000);
emit('when_ready', MASTER, {}, { cat: 'gunicorn' });

// Gunicorn spawns its workers a few tens of milliseconds apart. Each one's first writes copy a few stack and heap pages.
for (const pid of WORKERS) {
  pause(60_000);
  emit('fork', MASTER, { child: pid });
  pause(300);
  emit('post_fork', pid, {}, { cat: 'gunicorn' });
  pause(100);
  touch(pid, STACK, [29, 30, 31, 32], true);
  touch(pid, HEAP, [0, 9, 17, 40, 41, 63], true);
}

// The first request in each worker imports the URLconf, which Django loads lazily, and reads a few catalog entries.
const firstRequest = (pid: number, path: string) => {
  pause(400_000);
  slice('request', pid, { method: 'GET', path }, () => {
    touch(pid, TEXT, pick(30, 160), false);
    slice('import', pid, { module: 'app.urls' }, () => {
      mmap(pid, URLCONF, 256, { name: 'obmalloc arena', perms: 'rw-p' });
      touch(pid, URLCONF, Array.from({ length: 48 }, (_, page) => page), true);
    });
    touch(pid, CATALOG, [12, 13, 200], true);
    touch(pid, HEAP, [2, 3, 50, 51], true);
  });
};
// Reading every catalog entry updates each object's reference count, so the scan copies the whole catalog.
const scan = (pid: number) => {
  pause(400_000);
  slice('request', pid, { method: 'GET', path: '/scan' }, () => touch(pid, CATALOG, Array.from({ length: 256 }, (_, page) => page), true, 15));
};
pause(1_200_000);
firstRequest(WORKERS[0], '/lookup/42');
firstRequest(WORKERS[1], '/lookup/7');
scan(WORKERS[0]);
scan(WORKERS[1]);

// max_requests recycles the first worker: it exits, the master reaps it and forks a replacement that shares the master's pages again.
pause(600_000);
emit('exit', WORKERS[0], { code: 0 });
pause(1_000);
emit('reap', MASTER, { child: WORKERS[0] });
pause(5_000);
emit('fork', MASTER, { child: REPLACEMENT });
pause(300);
emit('post_fork', REPLACEMENT, {}, { cat: 'gunicorn' });
pause(100);
touch(REPLACEMENT, STACK, [29, 30, 31, 32], true);
firstRequest(REPLACEMENT, '/lookup/42');

mkdirSync(new URL('../public/recordings/', import.meta.url), { recursive: true });
writeFileSync(new URL('../public/recordings/synthetic-gunicorn-boot.json', import.meta.url), `{"traceEvents":[\n${events.map(event => JSON.stringify(event)).join(',\n')}\n]}\n`);
console.log(`Wrote ${events.length} events over ${(now / 1e6).toFixed(2)} s.`);
